--[[
  Negative (and a few positive) test vectors for linking and profile import, both sides
  (docs/vectors/account_flow_v1.json, DRAFT proposal for stackrivals.io; no new format: SRL1 / SRP1
  draft v1 and SR1 only).

    lua5.1 tests/account_flow_vectors.lua StackRivals tests > docs/vectors/account_flow_v1.json

  * addonImport: what the addon does with a pasted snapshot. Every expectation here is produced by
    running the real addon code (Core/Account.lua) in a simulated client, so the file can't drift
    from the code (tests/test_account.lua checks it is current).
  * websiteChecks: what the website must refuse. The addon can't run these (they need the website's
    database); they are the expected outcomes for web Claude's tests. Names of errors are proposals.

  Deterministic: seeded clients, fixed clock -> byte-identical JSON.
]]
local root, testdir = ...
root, testdir = root or "StackRivals", testdir or "tests"
local NS = assert(loadfile(testdir .. "/netsim.lua"))(root, testdir)
local SV = assert(loadfile(testdir .. "/sr1_vectors.lua"))(root, testdir)
local json, NULL = SV.json, SV.NULL

local M = {}
local T0 = 1793000000
local WEB_CODE = "A7K9P2X"

--- A client "Alice" at T0. setup: "none" | "pending" | "linked" (pending at T0, linked at T0 + 60).
local function client(seed, setup)
  local net = NS.new({ seed = seed })
  local c = net.add({ name = "Alice", saved = { seenHelp = true } })
  c.M.serverTime = T0
  local A = c.ns.AccountCodes
  local linkId
  if setup ~= "none" then
    assert(c.ns.Account.startLink(A.makeWebCode(WEB_CODE)))
    -- a fixed linkId: the random one differs between Lua 5.1 (CI, WoW) and 5.3 number arithmetic
    c.ns.Account.rec().pending.linkId = "k3v9q2m7x1aa"
    linkId = A.parseLinkRequest(c.ns.Account.requestCode()).linkId
    assert(linkId == "k3v9q2m7x1aa")
  end
  local base = {
    linkId = linkId or "abcdefghij12", player = "Alice-Realm", accountId = "acc_7f3k2", name = "Alice Stack",
    issued = T0 + 30, expires = T0 + 30 + 7 * 86400, level = 12, xp = 1240, xpNext = 2000, rank = "Gold II",
    season = "Season 3", seasonPct = 45, wins = 12, losses = 8, draws = 1, history = {},
    achUnlocked = 14, achTotal = 60, cosOwned = 5, cosEquipped = "Neon Grid",
  }
  local first
  if setup == "linked" then
    c.M.serverTime = T0 + 60
    first = A.profile(base)
    assert(c.ns.Account.import(first))
  end
  return c, A, base, first
end
local function with(base, o) local p = {}; for k, v in pairs(base) do p[k] = v end; for k, v in pairs(o or {}) do p[k] = v end; return p end
local function fields(code) local f = {}; for p in (code .. "."):gmatch("([^.]*)%.") do f[#f + 1] = p end; return f end

function M.build()
  local out = {
    format = "stackrivals.account-flow.v1-draft",
    note = "DRAFT proposal. addonImport is generated by running the addon (tests/account_flow_vectors.lua); websiteChecks are the outcomes the website must produce.",
    clock = { T0 = T0, pendingTtlSeconds = 15 * 60, clockSkewSeconds = 10 * 60, staleAfterSeconds = 7 * 86400 },
  }
  local cases = {}
  local function case(name, why, seed, setup, now, makeCode)
    local c, A, base, first = client(seed, setup)
    local code = makeCode(A, base, first, c.ns)
    c.M.serverTime = now
    local before = c.ns.Account.profileView()
    local okI, res = c.ns.Account.import(code)
    local after = c.ns.Account.profileView()
    cases[#cases + 1] = {
      name = name, why = why, setup = setup, now = now, code = code,
      expect = okI and { ok = true, result = res, verified = after.verified } or { ok = false, error = res },
      profileChanged = (before and before.asOf or NULL) ~= (after and after.asOf or NULL),
    }
  end
  local P = function(o) return function(A, base) return A.profile(with(base, o)) end end

  case("link_ok", "pending + snapshot with the same linkId, made after the request", 1, "pending", T0 + 60, P())
  case("update_ok", "linked + a newer snapshot", 2, "linked", T0 + 3600, P({ issued = T0 + 3000 }))
  case("wrong_character", "a snapshot for another character can't be imported here", 3, "pending", T0 + 60, P({ player = "Bob-Realm" }))
  case("other_link_while_pending", "linkId not the one this character asked for", 4, "pending", T0 + 60, P({ linkId = "zzzzzzzzzzzz" }))
  case("other_link_when_linked", "a snapshot from another link (another account) is refused", 5, "linked", T0 + 3600, P({ linkId = "zzzzzzzzzzzz", issued = T0 + 3000 }))
  case("made_before_request", "an old snapshot can't confirm a new link request (replay of an old confirmation)", 6, "pending", T0 + 60, P({ issued = T0 - 3600 }))
  case("future_dated", "issued more than the clock skew in the future", 7, "pending", T0 + 60, P({ issued = T0 + 3600 }))
  case("expired", "now is past expires + clock skew", 8, "linked", T0 + 30 + 8 * 86400, P({ issued = T0 + 100, expires = T0 + 200 }))
  case("older_than_current", "an older snapshot never replaces a newer one", 9, "linked", T0 + 3600, P({ issued = T0 + 10 }))
  case("same_twice", "the same snapshot again changes nothing", 10, "linked", T0 + 3600, function(_, _, first) return first end)
  case("no_request", "a snapshot without a link request on this character", 11, "none", T0 + 60, P())
  case("request_expired", "the link request is older than 15 minutes", 12, "pending", T0 + 16 * 60, P({ issued = T0 + 15 * 60 }))
  case("newer_format", "an unknown newer version is refused, never guessed", 13, "linked", T0 + 3600,
    function(A, base) return "SRP2" .. A.profile(with(base, { issued = T0 + 3000 })):sub(5) end)
  case("link_request_pasted", "the player's own SRL1 pasted in the snapshot box", 14, "pending", T0 + 60,
    function(A, base) return A.linkRequest({ code = A.makeWebCode(WEB_CODE), platform = "wow-forever", player = "Alice-Realm", linkId = base.linkId, addon = "0.9.0", engine = 1, issued = T0 }) end)
  case("typo", "one character changed: the check catches it", 15, "pending", T0 + 60, function(A, base)
    local s = A.profile(base); local i = 30
    return s:sub(1, i - 1) .. (s:sub(i, i) == "a" and "b" or "a") .. s:sub(i + 1)
  end)
  case("forged_but_rechecked", "XP raised and the check recomputed: ACCEPTED (the check only catches typos). Shown as UNVERIFIED, unlocks nothing; only a website signature can stop this", 16, "linked", T0 + 3600, function(A, base, _, ns)
    local f = fields(A.profile(with(base, { issued = T0 + 3000 })))
    table.remove(f)
    f[9] = "zzzzzz" -- xp (base 36): about 2.2 billion
    local body = table.concat(f, ".")
    return body .. "." .. string.format("%08x", ns.Prng.hashString(body))
  end)
  out.addonImport = cases

  out.websiteChecks = {
    { name = "code_unknown", step = "SRL1 pasted on the Link page", input = "a web code the website never issued", expect = "reject: code_unknown" },
    { name = "code_other_account", step = "SRL1 pasted on the Link page", input = "a valid code issued to ANOTHER logged-in account", expect = "reject: code_unknown (never reveal that it exists)" },
    { name = "code_expired", step = "SRL1", input = "the code is older than its lifetime (about 10 minutes)", expect = "reject: code_expired" },
    { name = "code_reused", step = "SRL1", input = "the same code a second time, after a successful link", expect = "reject: code_used" },
    { name = "code_brute_force", step = "Link page", input = "many wrong codes from one account or IP", expect = "rate limit; codes are 8 Crockford symbols with a check symbol" },
    { name = "request_bad_format", step = "SRL1", input = "every entry in account_v1.json linkRequestInvalid", expect = "reject with that error" },
    { name = "character_claimed_twice", step = "SRL1", input = "a second account links the same Name-Realm + platform", expect = "policy needed (C10): keep the first binding and flag, or allow one binding per account and mark both unverified" },
    { name = "character_not_proven", step = "binding", input = "any SRL1", expect = "store as CLAIMED: Name-Realm in a code is not proof of character ownership (only Battle.net OAuth would be)" },
    { name = "snapshot_for_other_link", step = "Export snapshot", input = "the website must only export a snapshot with the linkId and player of that binding", expect = "never export for another binding" },
    { name = "result_unlinked", step = "Import result (SR1R)", input = "link field '-'", expect = "board only as 'Name-Realm (unlinked)'; earns nothing for anyone" },
    { name = "result_other_account", step = "Import result", input = "an SR1R whose link code belongs to another account's binding", expect = "reject: link_mismatch (never credit the importing account)" },
    { name = "result_link_reused", step = "Import result", input = "a second SR1R with the same one-time link code", expect = "reject: link_used (the link code inside a result is single-use)" },
    { name = "result_player_mismatch", step = "Import result", input = "playerHex not the Name-Realm of the binding the link code belongs to", expect = "reject: player_mismatch" },
    { name = "result_duplicate_run", step = "Import result", input = "the same run (runKey) under another name or account", expect = "reject: duplicate_run, flag for review" },
    { name = "result_replay_fails", step = "Import result", input = "every SR1 replay error in sr1.json (claim_mismatch, hash_mismatch, over_time_cap, faster_than_clock, inhuman_input_rate, inputs_after_topout, expired)", expect = "stored as rejected, never ranked, never rewarded" },
    { name = "reward_without_limits", step = "rewards", input = "a server_verified result beyond the daily cap", expect = "board yes, reward no (WOW_PROGRESSION_SPEC.md section 4)" },
    { name = "peer_checked_reward", step = "rewards", input = "a WoW duel or Loot Duel result", expect = "never imported for rewards (no export exists)" },
  }
  return out
end

function M.text() return json(M.build()) .. "\n" end

if arg and arg[0] and arg[0]:match("account_flow_vectors%.lua$") then io.write(M.text()) end
return M
