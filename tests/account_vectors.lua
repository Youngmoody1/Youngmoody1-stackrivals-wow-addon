--[[
  Builds the shared account-code test vectors (docs/vectors/account_v1.json, DRAFT v1) with the Lua
  implementation (Net/AccountCodes.lua). The TypeScript reference (tools/contract/account.ts) must
  reproduce every expectation: bun tools/contract/check_account_vectors.ts docs/vectors/account_v1.json

    lua5.1 tests/account_vectors.lua StackRivals tests > docs/vectors/account_v1.json

  Deterministic: same input -> byte-identical JSON (tests/test_account.lua checks the file is current).
]]
local root, testdir = ...
root, testdir = root or "StackRivals", testdir or "tests"
local H = dofile(testdir .. "/harness.lua")
local ns = H.load(root, { "Engine/Prng.lua", "Engine/Pieces.lua", "Engine/Engine.lua", "Net/Protocol.lua", "Net/Codes.lua", "Net/AccountCodes.lua" })
local A = ns.AccountCodes
local SV = assert(loadfile(testdir .. "/sr1_vectors.lua"))(root, testdir)
local json, NULL = SV.json, SV.NULL

local M = {}
local T0 = 1793000000

local function withCheck(body) return body .. "." .. string.format("%08x", ns.Prng.hashString(body)) end
local function fields(code) local f = {}; for p in (code .. "."):gmatch("([^.]*)%.") do f[#f + 1] = p end; return f end
--- Replace field i (1-based) of a code and re-sign the check, so only that field is wrong.
local function mutate(code, i, value)
  local f = fields(code)
  table.remove(f) -- old check
  f[i] = value
  return withCheck(table.concat(f, "."))
end

function M.build()
  local out = { format = "stackrivals.account.v1-draft", note = "DRAFT until agreed by stackrivals.io. Generated by tests/account_vectors.lua." }

  -- web link codes
  out.webCodes = {}
  for _, seven in ipairs({ "A7K9P2X", "0000000", "ZZZZZZZ", "K4M9TQ2", "1234567", "QRSTVWX" }) do
    local code = A.makeWebCode(seven)
    out.webCodes[#out.webCodes + 1] = { seven = seven, code = code, pretty = A.prettyWebCode(code) }
  end
  local good = A.makeWebCode("A7K9P2X")
  out.webCodeInputs = {}
  local inputs = {
    { good, good }, { A.prettyWebCode(good), good }, { A.prettyWebCode(good):lower(), good }, { " a7k9 - p2xj ", good },
    { "OOIL" .. A.makeWebCode("0011ABC"):sub(5), A.makeWebCode("0011ABC") },
    { "A7K9P2XK", nil, "check" }, { "A7K9P2X", nil, "format" }, { "A7K9P2XJJ", nil, "format" }, { "A7K9P2UJ", nil, "format" },
    { "", nil, "format" }, { "A7K9-P2X!", nil, "format" },
  }
  for _, c in ipairs(inputs) do
    local r, why = A.parseWebCode(c[1])
    assert(r == c[2] and (c[2] or why == c[3]), "web code vector mismatch: " .. c[1])
    out.webCodeInputs[#out.webCodeInputs + 1] = { input = c[1], code = r or NULL, error = why or NULL }
  end

  -- link requests
  local reqs = {
    { code = good, platform = "wow-classic", player = "Alice-Realm", linkId = "k3v9q2m7x1aa", addon = "0.6.1", engine = 1, issued = T0 },
    { code = A.makeWebCode("ZZZZZZZ"), platform = "wow-forever", player = "Søren-Firemaw", linkId = "000000000000", addon = "1.0.0", engine = 12, issued = 0 },
    { code = A.makeWebCode("0000000"), platform = "wow-retail", player = "Bob-Argent'Dawn", linkId = "zzzzzzzzzzzz", addon = "dev", engine = 9999, issued = 2000000000 },
  }
  out.linkRequests = {}
  for _, r in ipairs(reqs) do
    local code = A.linkRequest(r)
    local back = assert(A.parseLinkRequest(code))
    out.linkRequests[#out.linkRequests + 1] = { code = code, decoded = {
      code = back.code, platform = back.platform, player = back.player, linkId = back.linkId, addon = back.addon, engine = back.engine, issued = back.issued } }
  end
  local base = A.linkRequest(reqs[1])
  local badReq = {
    { base:sub(1, -2) .. (base:sub(-1) == "0" and "1" or "0"), "check" },
    { "SRL2" .. base:sub(5), "version" }, { "SRX1" .. base:sub(5), "format" }, { base:sub(1, 30), "fields" }, { "", "empty" },
    { mutate(base, 2, "A7K9P2XK"), "code" }, { mutate(base, 3, "wow-tbc"), "platform" }, { mutate(base, 4, "4141"), "player" },
    { mutate(base, 5, "K3V9Q2M7X1AA"), "linkId" }, { mutate(base, 5, "short"), "linkId" }, { mutate(base, 6, "0.6.1"), "fields" },
    { mutate(base, 7, "0"), "engine" }, { mutate(base, 8, "0abc"), "issued" }, { base .. "\194\160", "chars" },
  }
  out.linkRequestInvalid = {}
  for _, c in ipairs(badReq) do
    local r, why = A.parseLinkRequest(c[1])
    assert(r == nil and why == c[2], "link request vector: want " .. c[2] .. " got " .. tostring(why))
    out.linkRequestInvalid[#out.linkRequestInvalid + 1] = { code = c[1], error = why }
  end

  -- profile snapshots
  local function prof(o)
    local p = { linkId = "k3v9q2m7x1aa", player = "Alice-Realm", accountId = "acc_7f3k2", name = "Alice Stack", issued = T0 + 60, expires = T0 + 60 + 7 * 86400,
      level = 12, xp = 1240, xpNext = 2000, rank = "Gold II", season = "Season 3", seasonPct = 45, wins = 12, losses = 8, draws = 1,
      history = { { mode = "b120", res = "w", my = 12300, their = 9800, at = T0 - 3600 } }, achUnlocked = 14, achTotal = 60, cosOwned = 5, cosEquipped = "Neon Grid" }
    for k, v in pairs(o or {}) do if v == NULL then p[k] = nil else p[k] = v end end
    return p
  end
  local pcases = {
    prof(),
    prof({ rank = NULL, season = NULL, history = {}, achUnlocked = NULL, achTotal = NULL, cosOwned = NULL, cosEquipped = NULL, level = 0, xp = 0, xpNext = 0, seasonPct = 0, wins = 0, losses = 0, draws = 0 }),
    prof({ name = "Søren Æblegrød", player = "Søren-Firemaw", rank = "Diamant", cosEquipped = NULL, sig = "abcDEF_123-xyz00" }),
    prof({ history = (function() local h = {}; for i = 1, 10 do h[i] = { mode = (i % 2 == 0) and "s180" or "daily", res = ({ "w", "l", "d" })[i % 3 + 1], my = i * 1000, their = 999999999, at = T0 - i } end; return h end)(),
      level = 9999, xp = 1e12, xpNext = 1e12, seasonPct = 100, wins = 1e9, losses = 1e9, draws = 1e9, achUnlocked = 9999, achTotal = 9999, cosOwned = 99999,
      expires = T0 + 60 + 30 * 86400 }),
  }
  out.profiles = {}
  for _, p in ipairs(pcases) do
    local code = A.profile(p)
    local d = assert(A.parseProfile(code))
    local hist = {}
    for i, h in ipairs(d.history) do hist[i] = { mode = h.mode, res = h.res, my = h.my, their = h.their, at = h.at } end
    out.profiles[#out.profiles + 1] = { code = code, decoded = {
      linkId = d.linkId, player = d.player, accountId = d.accountId, name = d.name, issued = d.issued, expires = d.expires,
      level = d.level, xp = d.xp, xpNext = d.xpNext, rank = d.rank or NULL, season = d.season or NULL, seasonPct = d.seasonPct,
      wins = d.wins, losses = d.losses, draws = d.draws, history = hist, achUnlocked = d.achUnlocked or NULL, achTotal = d.achTotal or NULL,
      cosOwned = d.cosOwned or NULL, cosEquipped = d.cosEquipped or NULL, sig = d.sig or NULL } }
  end
  local pb = A.profile(prof())
  local hx = function(s) return ns.Codes.hex(s) end
  local badProf = {
    { pb:sub(1, -2) .. (pb:sub(-1) == "0" and "1" or "0"), "check" }, { "SRP2" .. pb:sub(5), "version" },
    { ns.Codes.challenge("b120", "abc"), "wrong_kind" }, { "hello", "format" }, { "", "empty" }, { string.rep("x", 4097), "size" },
    { pb:sub(1, 60), "fields" },
    { mutate(pb, 2, "K3V9"), "linkId" }, { mutate(pb, 3, "4141"), "player" }, { mutate(pb, 4, "a"), "accountId" },
    { mutate(pb, 4, "ACC_UPPER"), "accountId" }, { mutate(pb, 5, hx("Bad\nName")), "name" }, { mutate(pb, 5, hx(string.rep("x", 33))), "name" },
    { mutate(pb, 5, "-"), "name" }, { mutate(pb, 7, fields(pb)[6]), "time" }, { mutate(pb, 8, "7ps"), "numbers" },
    { mutate(pb, 8, "0c"), "numbers" }, { mutate(pb, 11, hx(string.rep("x", 25))), "rank" }, { mutate(pb, 12, "zz"), "season" },
    { mutate(pb, 13, "101"), "season" }, { mutate(pb, 17, "b120-x-1-1-1"), "history" }, { mutate(pb, 17, "B120-w-1-1-1"), "history" },
    { mutate(pb, 18, "1o-1n"), "achievements" }, { mutate(pb, 19, "5-zz"), "cosmetics" }, { mutate(pb, 20, "short"), "sig" },
    { mutate(pb, 20, "has.dot.inside.xx"), "fields" },
  }
  out.profileInvalid = {}
  for _, c in ipairs(badProf) do
    local r, why = A.parseProfile(c[1])
    assert(r == nil and why == c[2], "profile vector: want " .. c[2] .. " got " .. tostring(why) .. " for " .. c[1]:sub(1, 40))
    out.profileInvalid[#out.profileInvalid + 1] = { code = c[1], error = why }
  end
  return out
end

function M.text() return json(M.build()) .. "\n" end

if arg and arg[0] and arg[0]:match("account_vectors%.lua$") then io.write(M.text()) end
return M
