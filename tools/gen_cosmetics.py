#!/usr/bin/env python3
"""Generate StackRivals/Core/CosmeticsCatalog.lua from the website's docs/vectors/cosmetics_catalog_v1.json.

The JSON is copied unchanged from the website repo; this file only turns it into Lua so the addon can show
names, slots and rarity. Display only: prices and availability are the website's (the Shop isn't open).
Run: python3 tools/gen_cosmetics.py   (tests/test_cosmetics.lua checks the Lua file is current)
"""
import json, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "docs", "vectors", "cosmetics_catalog_v1.json")
dst = os.path.join(root, "StackRivals", "Core", "CosmeticsCatalog.lua")
d = json.load(open(src, encoding="utf-8"))
def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
lines = [
    "--[[",
    "  StackRivals - the website's cosmetics catalog (GENERATED by tools/gen_cosmetics.py from",
    "  docs/vectors/cosmetics_catalog_v1.json, copied unchanged from stackrivals.io). Do not edit by hand.",
    "  Source: " + d.get("source", ""),
    "  Display only: names, slots and rarity for the Collection tab. Ownership and equipped items come only",
    "  from the website's SRP2 code; nothing is applied in WoW from an unverified code; nothing is sold here.",
    "]]",
    "local _, ns = ...",
    "ns = ns or {}",
    "",
    "local Cat = { items = {}, byId = {} }",
    "ns.CosmeticsCatalog = Cat",
    "Cat.SLOTS = { \"skin\", \"frame\", \"victory\" }",
    "Cat.SHOP_OPEN = false -- the website's Shop isn't open yet: purchasable items show as Upcoming",
    "",
    "local items = {",
]
for it in d["items"]:
    price = "nil" if it.get("priceShards") is None else str(int(it["priceShards"]))
    lines.append("  { id = %s, name = %s, slot = %s, rarity = %s, acquisition = %s, price = %s }," % (
        q(it["id"]), q(it["name"]), q(it["slot"]), q(it["rarity"]), q(it["acquisition"]), price))
lines += [
    "}",
    "for i, it in ipairs(items) do Cat.items[i] = it; Cat.byId[it.id] = it end",
    "",
    "return Cat",
    "",
]
out = "\n".join(lines)
if "--check" in sys.argv:
    cur = open(dst, encoding="utf-8").read() if os.path.exists(dst) else ""
    sys.exit(0 if cur == out else 1)
open(dst, "w", encoding="utf-8").write(out)
print("wrote", os.path.relpath(dst, root), len(d["items"]), "items")
