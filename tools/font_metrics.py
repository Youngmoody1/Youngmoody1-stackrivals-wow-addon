"""Writes tests/fontmetrics.lua: advance widths (in em) of printable ASCII for the bundled display
fonts, measured from the TTF files. The layout tests use them, so text-fit checks for the brand
font are exact instead of estimated (WoW's own body font is not available here: still estimated).

    python3 tools/font_metrics.py
"""
from PIL import ImageFont

FONTS = {"ChakraPetch-Bold": "StackRivals/Media/Fonts/ChakraPetch-Bold.ttf",
         "ChakraPetch-BoldItalic": "StackRivals/Media/Fonts/ChakraPetch-BoldItalic.ttf"}
out = ["-- GENERATED by tools/font_metrics.py from the bundled TTF files. Do not edit.", "return {"]
for name, path in FONTS.items():
    f = ImageFont.truetype(path, 1000)
    widths = ", ".join(f'[{c}]={f.getlength(chr(c)) / 1000:.4f}' for c in range(32, 127))
    out.append(f'  ["{name}"] = {{ {widths} }},')
out.append("}")
open("tests/fontmetrics.lua", "w").write("\n".join(out) + "\n")
print("ok")
